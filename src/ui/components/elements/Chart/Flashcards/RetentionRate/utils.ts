/**
 * Extract per-day retention rate from stats.progress,
 * sorted chronologically.
 * Returns empty array when progress is empty or null.
 */
export function computeRetentionRateOverTime(
	progress: Record<string, DailyProgress>,
): RetentionRatePoint[] {
	return Object.entries(progress)
		.map(([dateStr, day]) => ({
			date: new Date(dateStr),
			retention: day.retention_rate,
		}))
		.sort((a, b) => a.date.getTime() - b.date.getTime());
}
